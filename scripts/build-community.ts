import { readFileSync, writeFileSync } from 'node:fs';
import { importTheme } from '../src/theme-import/index.ts';
import { repairDraft, draftIssues } from '../src/studio/model.ts';
const curated=['catppuccin-mocha','nord','rose-pine'];
const catalog=curated.map(id=>{
  const source=readFileSync(`tests/fixtures/themes/${id}.yaml`,'utf8');
  const imported=importTheme(source,'base16');
  const draft=repairDraft(imported.theme);
  if(draftIssues(draft).length)throw Error('Unreadable community adaptation: '+id);
  return {id,author:source.match(/^author:\s*"(.+)"/m)?.[1]??'Tinted Theming',url:`https://github.com/tinted-theming/schemes/blob/spec-0.11/base16/${id}.yaml`,theme:{...draft,source:'community-base16'},adapted:JSON.stringify(imported.theme.colors)!==JSON.stringify(draft.colors)};
});
writeFileSync('src/workspace/community.ts',`// Generated by scripts/build-community.ts; source attribution: THIRD_PARTY_NOTICES.md\nimport type { CustomThemeConfig } from '../config/types.ts';\nexport const COMMUNITY_THEMES: Array<{id:string;author:string;url:string;theme:CustomThemeConfig;adapted:boolean}> = ${JSON.stringify(catalog,null,2)};\n`);

/**
 * Minimal bilingual copy for the settings UI (zh + en). Kept inline rather
 * than through the locale service so the plugin has zero hard locale
 * dependency and still degrades gracefully if the locale plugin is absent.
 */

export type Lang = 'zh' | 'en';

export function detectLang(): Lang {
  if (typeof navigator !== 'undefined') {
    const lang = (navigator.language || '').toLowerCase();
    if (lang.startsWith('zh')) return 'zh';
  }
  return 'en';
}

